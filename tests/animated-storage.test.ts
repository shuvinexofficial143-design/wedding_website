import {createAnimated,updateAnimated,setAnimatedPublished,privateAnimatedById,listAnimatedPublic,linkAnimatedOrder,markAnimatedPaid,changeAnimatedJob,privateAnimatedJob,ownedAnimatedJob} from '../src/lib/animated/repository';
import {beginAsset,assetById,completeAsset} from '../src/lib/storage/assets';
import {putObject,deleteObject} from '../src/lib/storage/objects';
import {hashBytes,validateMp4} from '../src/lib/storage/validate';
const dir=mkdtempSync(join(tmpdir(),'animated-storage-'));
process.env.DATABASE_PATH=join(dir,'db.sqlite');process.env.ASSET_STORAGE='local';process.env.ASSET_LOCAL_DIR=join(dir,'objects');
test('uploaded thumbnail ownership, immutable purchased Canva snapshot, concurrent updates and private MP4 delivery',async()=>{
 const admin={id:randomUUID(),email:'admin@example.test',role:'admin'},buyer={id:randomUUID(),email:'buyer@example.test',role:'customer'};
 for(const u of [admin,buyer])await db().prepare('INSERT INTO users(id,email,password,role,created) VALUES(?,?,?,?,?)').run(u.id,u.email,'fixture',u.role,Date.now());
 async function upload(owner:typeof admin,purpose:string,bytes:Buffer,mime:string){const pending=await beginAsset(owner,{purpose,mime,size:bytes.length,sha256:hashBytes(bytes)});const asset=(await assetById(pending.id))!;await putObject(asset.object_key,bytes,mime);return completeAsset(asset);}
 const png=await sharp({create:{width:30,height:30,channels:3,background:'#bf9060'}}).png().toBuffer();
 const thumb=await upload(admin,'thumbnail',png,'image/png');
 const input={styleNumber:'ANI-INTEGRATION',name:'Integration floral',category:'wedding',pricePaise:59900,thumbnailUrl:'/api/assets/'+thumb.id,youtubeUrl:'https://youtu.be/dQw4w9WgXcQ',canvaUrl:'https://www.canva.com/design/MASTER/edit'};
 await assert.rejects(()=>createAnimated(buyer,input),/owned/);
 const template=await createAnimated(admin,input);
 await assert.rejects(()=>createAnimated(admin,input),/UNIQUE/);
 assert.equal((await listAnimatedPublic()).length,0);
 await setAnimatedPublished(admin,template.id,1,'published');
 const publicTemplate=(await listAnimatedPublic())[0];assert.equal(JSON.stringify(publicTemplate).includes('canva'),false);
 const orderId=randomUUID();await db().prepare('INSERT INTO orders(id,user_id,product_id,amount,phone,details,created) VALUES(?,?,?,?,?,?,?)').run(orderId,buyer.id,template.id,59900,'9876543210',JSON.stringify({partnerA:'काव्या',partnerB:'Rahul'}),Date.now());
 await linkAnimatedOrder(orderId,publicTemplate);
 await assert.rejects(()=>changeAnimatedJob(admin,orderId,0,'editing'),/paid/);
 await db().prepare("UPDATE orders SET status='paid' WHERE id=?").run(orderId);await markAnimatedPaid(orderId);
 const at=(await privateAnimatedJob(orderId))!.paid_at;await markAnimatedPaid(orderId);assert.equal((await privateAnimatedJob(orderId))!.paid_at,at);
 const updates=await Promise.allSettled([updateAnimated(admin,template.id,2,{...input,name:'Changed'}),updateAnimated(admin,template.id,2,{...input,name:'Other'})]);assert.equal(updates.filter(r=>r.status==='fulfilled').length,1);
 assert.equal((await privateAnimatedJob(orderId))!.template_name,input.name);
 await assert.rejects(()=>changeAnimatedJob(admin,orderId,0,'copy',input.canvaUrl),/independent/);
 await changeAnimatedJob(admin,orderId,0,'copy','https://www.canva.com/design/COPY/edit');
 await changeAnimatedJob(admin,orderId,1,'editing');
 await assert.rejects(()=>changeAnimatedJob(admin,orderId,2,'delivered',undefined,input.canvaUrl),/Private Canva/);
 const bytes=mp4Fixture;
 const video=await upload(admin,'video',bytes,'video/mp4');
 await assert.rejects(()=>changeAnimatedJob(admin,orderId,2,'delivered',undefined,undefined,thumb.id),/MP4/);
 await deleteObject(video.object_key);
 await assert.rejects(()=>changeAnimatedJob(admin,orderId,2,'delivered',undefined,undefined,video.id));
 assert.equal((await privateAnimatedJob(orderId))!.delivered_at,null);
 await putObject(video.object_key,bytes,'video/mp4');
 await changeAnimatedJob(admin,orderId,2,'delivered',undefined,undefined,video.id);
 assert.equal((await getOrder(orderId))!.video_path,'asset:'+video.id);
 const owned=await ownedAnimatedJob(orderId,buyer.id);assert.equal(owned!.delivery_url,'/api/orders/'+orderId+'/video');assert.equal(JSON.stringify(owned).includes('canva'),false);
 assert.equal(await ownedAnimatedJob(orderId,admin.id),undefined);
 await setAnimatedPublished(admin,template.id,(await privateAnimatedById(template.id))!.revision,'unpublished');assert.equal((await listAnimatedPublic()).length,0);assert.ok(await ownedAnimatedJob(orderId,buyer.id));
 await assert.rejects(()=>changeAnimatedJob(admin,orderId,3,'delivered',undefined,undefined,video.id),/already delivered/);
});

test('MP4 validation rejects header-only, truncated and oversized box declarations',()=>{
 assert.doesNotThrow(()=>validateMp4(mp4Fixture));
 assert.throws(()=>validateMp4(mp4Fixture.subarray(0,32)));
 assert.throws(()=>validateMp4(mp4Fixture.subarray(0,mp4Fixture.length-5)));
 const corrupt=Buffer.from(mp4Fixture);corrupt.writeUInt32BE(0xffffffff,0);assert.throws(()=>validateMp4(corrupt));
});
